"""第 1 讲练习实现：椭圆曲线运算与地址派生。

判分：pytest lecture-01/tests
"""
from Crypto.Hash import keccak

# 小曲线 y² = x³ + 7 (mod 17)，生成元 G = (15, 13)，一共 18 个点
TOY_P = 17
TOY_G = (15, 13)

# secp256k1：同样是 y² = x³ + 7，只是模数 p 大得多
P = 2**256 - 2**32 - 977
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
G = (0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
     0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8)

# 无穷远点 O 用 None 表示


def inv(a, p):
    """a 在模 p 下的逆元。"""
    return pow(a, -1, p)


def add(A, B, p):
    """曲线 y² = x³ + 7 (mod p) 上的点加法 A + B。"""
    if A is None:
        return B
    if B is None:
        return A

    x1, y1 = A
    x2, y2 = B

    # Two points with the same x-coordinate and opposite y-coordinates add
    # to the point at infinity. This also covers doubling a point with y = 0.
    if x1 == x2 and (y1 + y2) % p == 0:
        return None

    if A == B:
        slope = (3 * x1 * x1) * inv(2 * y1, p) % p
    else:
        slope = (y2 - y1) * inv(x2 - x1, p) % p

    x3 = (slope * slope - x1 - x2) % p
    y3 = (slope * (x1 - x3) - y1) % p
    return x3, y3


def mul(k, A, p):
    """标量乘法 k·A，用“倍加”法。"""
    if k < 0:
        if A is None:
            return None
        return mul(-k, (A[0], -A[1] % p), p)

    result = None
    addend = A
    while k:
        if k & 1:
            result = add(result, addend, p)
        addend = add(addend, addend, p)
        k >>= 1
    return result


def brute_force(Q, p=TOY_P, g=TOY_G):
    """返回满足 k·G = Q 的最小正整数 k；若 Q 不在生成子群内则报错。"""
    candidate = g
    k = 1
    while candidate != Q:
        if candidate is None:
            raise ValueError("Q is not in the subgroup generated by g")
        candidate = add(candidate, g, p)
        k += 1
    return k


def address(priv):
    """进阶：私钥 → 以太坊地址（小写，带 0x）。"""
    if not 1 <= priv < N:
        raise ValueError("private key must be in the range [1, N)")

    public_key = mul(priv, G, P)
    encoded = public_key[0].to_bytes(32, "big") + public_key[1].to_bytes(32, "big")
    digest = keccak.new(digest_bits=256, data=encoded).digest()
    return "0x" + digest[-20:].hex()
